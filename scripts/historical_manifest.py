"""Generate or check the SHA-256 manifest of protected historical artifacts.

The manifest pins the bytes of every historical research artifact (v0.2.0 experiment outputs,
reproducibility bundles, the v0.2 technical report) and the frozen task-version 1.0.0 source.
Hashes are taken from the git objects at the release tag, not from the working tree, so the tag
is the authoritative reference.

    uv run python scripts/historical_manifest.py generate   # (re)write the manifest from the tag
    uv run python scripts/historical_manifest.py check      # verify the working tree against it

The manifest uses `sha256sum` format, so `sha256sum -c research/HISTORICAL_SHA256SUMS` also works.
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess  # nosec B404 - fixed git invocations only
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "research" / "HISTORICAL_SHA256SUMS"
REFERENCE_TAG = "v0.2.0"
PROTECTED_PATHS = (
    "research/TRACEFORGE_TECHNICAL_REPORT.md",
    "research/results",
    "src/traceforge/modules/tasks/families/legacy_1_0_0.py",
)
HEADER = (
    f"# SHA-256 of protected historical artifacts, computed from git tag {REFERENCE_TAG}.\n"
    "# Generated by scripts/historical_manifest.py; verified in CI by\n"
    "# tests/integration/test_historical_integrity.py. Never edit these files or this manifest.\n"
)


def _git(*args: str) -> bytes:
    return subprocess.run(  # nosec B603 B607 - fixed git arguments, no shell
        ["git", *args], cwd=ROOT, check=True, capture_output=True
    ).stdout


def tag_hashes(tag: str = REFERENCE_TAG) -> dict[str, str]:
    """SHA-256 of each protected file's blob at ``tag`` (exact committed bytes)."""
    names = _git("ls-tree", "-r", "--name-only", tag, "--", *PROTECTED_PATHS).decode().split()
    return {n: hashlib.sha256(_git("cat-file", "blob", f"{tag}:{n}")).hexdigest() for n in names}


def read_manifest(path: Path = MANIFEST) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            digest, name = line.split(maxsplit=1)
            out[name.strip()] = digest
    return out


def check(path: Path = MANIFEST) -> list[str]:
    """Problems with the working tree relative to the manifest (empty when intact)."""
    problems = []
    for name, digest in sorted(read_manifest(path).items()):
        f = ROOT / name
        if not f.is_file():
            problems.append(f"missing {name}")
        elif hashlib.sha256(f.read_bytes()).hexdigest() != digest:
            problems.append(f"modified {name}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("generate", "check"))
    args = parser.parse_args()
    if args.command == "generate":
        hashes = tag_hashes()
        body = "".join(f"{d}  {n}\n" for n, d in sorted(hashes.items()))
        MANIFEST.write_text(HEADER + body, encoding="utf-8", newline="\n")
        print(f"wrote {len(hashes)} entries to {MANIFEST.relative_to(ROOT)}")
        return 0
    problems = check()
    for p in problems:
        print(p)
    print("OK" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
