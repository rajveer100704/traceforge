"""Immutable, provenance-preserving dataset construction (Parquet + manifest)."""

from __future__ import annotations

import io
import json
from collections import Counter
from collections.abc import Callable
from dataclasses import dataclass

import pyarrow as pa
import pyarrow.parquet as pq

from traceforge.contracts.common import SCHEMA_VERSION, sha256_bytes, sha256_json
from traceforge.contracts.datasets import (
    CurationLevel,
    DatasetKind,
    DatasetManifest,
    PartitionFile,
    QualityAssessment,
    QualityStatus,
)
from traceforge.contracts.traces import Outcome, Trajectory
from traceforge.modules.training.sft.formatting import (
    FORMAT_VERSION,
    assistant_mask,
    trajectory_to_messages,
)

TRANSFORMATION_ID = "traceforge.dataset_builder"
TRANSFORMATION_VERSION = "1.0.0"
SPLIT_POLICY = "task-split-or-hash"
SPLIT_POLICY_VERSION = "1"
TRAINING_SPLITS = ("train", "validation")

SFT_SCHEMA = pa.schema(
    [
        ("trajectory_id", pa.string()),
        ("content_hash", pa.string()),
        ("task_id", pa.string()),
        ("split", pa.string()),
        ("outcome", pa.string()),
        ("quality_score", pa.float64()),
        ("labels", pa.list_(pa.string())),
        ("messages_json", pa.string()),
        ("assistant_targets", pa.int32()),
        ("format_version", pa.string()),
    ]
)


@dataclass
class BuiltDataset:
    manifest: DatasetManifest
    partitions: dict[str, bytes]  # name -> parquet bytes
    records: list[tuple[str, str, str, str]]  # (trajectory_id, content_hash, split, quality status)
    rejection_summary: dict[str, int]


def select_for_level(
    pairs: list[tuple[Trajectory, QualityAssessment]], level: CurationLevel
) -> tuple[list[tuple[Trajectory, QualityAssessment]], Counter[str]]:
    rejected: Counter[str] = Counter()
    out = []
    for t, a in pairs:
        if level == CurationLevel.D1_RAW:
            ok = a.status != QualityStatus.QUARANTINED
        elif level == CurationLevel.D2_SCHEMA_VALID:
            ok = a.status == QualityStatus.ACCEPTED
        elif level == CurationLevel.D3_VERIFIED_SUCCESS:
            ok = a.status == QualityStatus.ACCEPTED and "verified_success" in a.labels
        else:
            ok = a.status == QualityStatus.ACCEPTED and (
                "verified_success" in a.labels or "informative_failure" in a.labels
            )
        if ok:
            out.append((t, a))
        else:
            rejected[f"excluded_by_{level.value}:{a.status.value}"] += 1
    return out, rejected


def assign_split(t: Trajectory, task_split: Callable[[str], str | None]) -> str | None:
    if t.task_id:
        split = task_split(t.task_id)
        if split is not None:
            return split if split in TRAINING_SPLITS else None  # held-out tasks never train
    bucket = int(t.content_hash[:8], 16) % 10
    return "validation" if bucket == 0 else "train"


def _parquet(rows: list[dict[str, object]], schema: pa.Schema) -> bytes:
    table = pa.Table.from_pylist(rows, schema=schema)
    buf = io.BytesIO()
    pq.write_table(table, buf, compression="snappy", write_statistics=False)
    return buf.getvalue()


class DatasetBuilder:
    def build(
        self,
        name: str,
        pairs: list[tuple[Trajectory, QualityAssessment]],
        *,
        kind: DatasetKind = DatasetKind.SFT,
        level: CurationLevel = CurationLevel.D3_VERIFIED_SUCCESS,
        task_split: Callable[[str], str | None],
        license_: str = "CC-BY-4.0 (synthetic TraceForge data)",
        provenance: str = "synthetic trajectories generated by TraceForge",
        code_commit: str | None = None,
        parents: tuple[str, ...] = (),
    ) -> BuiltDataset:
        selected, rejected = select_for_level(pairs, level)
        rows_by_split: dict[str, list[dict[str, object]]] = {s: [] for s in TRAINING_SPLITS}
        records: list[tuple[str, str, str, str]] = []
        for t, a in sorted(selected, key=lambda p: p[0].content_hash):
            split = assign_split(t, task_split)
            if split is None:
                rejected["split_leakage_excluded"] += 1
                continue
            messages = trajectory_to_messages(t)
            rows_by_split[split].append(
                {
                    "trajectory_id": str(t.trajectory_id),
                    "content_hash": t.content_hash,
                    "task_id": t.task_id or "",
                    "split": split,
                    "outcome": t.outcome.value,
                    "quality_score": a.score,
                    "labels": list(a.labels),
                    "messages_json": json.dumps(messages, sort_keys=True, default=str),
                    "assistant_targets": sum(assistant_mask(messages)),
                    "format_version": FORMAT_VERSION,
                }
            )
            records.append((str(t.trajectory_id), t.content_hash, split, a.status.value))
        partitions: dict[str, bytes] = {}
        files: list[PartitionFile] = []
        for split, rows in rows_by_split.items():
            data = _parquet(rows, SFT_SCHEMA)
            fname = f"{split}.parquet"
            partitions[fname] = data
            files.append(
                PartitionFile(
                    name=fname,
                    split=split,
                    path=fname,
                    sha256=sha256_bytes(data),
                    num_rows=len(rows),
                )
            )
        included = {r[0] for r in records}
        counts_outcome = Counter(
            t.outcome.value for t, _ in selected if str(t.trajectory_id) in included
        )
        counts_quality = Counter(a.status.value for _, a in pairs)
        sources = tuple(sorted((r[0], r[1]) for r in records))
        content_hash = sha256_json(
            {
                "name": name,
                "kind": kind.value,
                "level": level.value,
                "sources": sources,
                "transformation": [TRANSFORMATION_ID, TRANSFORMATION_VERSION, FORMAT_VERSION],
                "split_policy": [SPLIT_POLICY, SPLIT_POLICY_VERSION],
                "partitions": [(f.name, f.sha256) for f in files],
                "parents": list(parents),
            }
        )
        manifest = DatasetManifest(
            dataset_id=name,
            version=f"v-{content_hash[:12]}",
            kind=kind,
            curation_level=level,
            schema_version=SCHEMA_VERSION,
            source_trajectories=sources,
            transformation_id=TRANSFORMATION_ID,
            transformation_version=TRANSFORMATION_VERSION,
            code_commit=code_commit,
            split_policy=SPLIT_POLICY,
            split_policy_version=SPLIT_POLICY_VERSION,
            counts_by_outcome=dict(sorted(counts_outcome.items())),
            counts_by_quality=dict(sorted(counts_quality.items())),
            rejection_summary=dict(sorted(rejected.items())),
            license=license_,
            provenance=provenance,
            partitions=tuple(files),
            parent_versions=parents,
            content_hash=content_hash,
        )
        return BuiltDataset(
            manifest=manifest,
            partitions=partitions,
            records=records,
            rejection_summary=dict(rejected),
        )


def read_partition(data: bytes) -> list[dict[str, object]]:
    return pq.read_table(io.BytesIO(data)).to_pylist()


def outcome_counts(rows: list[dict[str, object]]) -> dict[str, int]:
    return dict(Counter(str(r["outcome"]) for r in rows))


__all__ = ["BuiltDataset", "DatasetBuilder", "Outcome", "read_partition"]
